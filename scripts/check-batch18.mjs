import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
let failed = false;
const check = (ok, name) => { console.log(`${ok ? 'PASS' : 'FAIL'}: ${name}`); if (!ok) failed = true; };
const schema = read('prisma/schema.prisma');
const migration = read('prisma/migrations/202610140018_provider_webhook_idempotency/migration.sql');
const safety = read('apps/api/src/finance/providers/provider-safety.ts');
const tests = read('apps/api/src/finance/providers/provider-safety.spec.ts');
check(/provider\s*=\s*"mysql"/.test(schema), 'Prisma datasource remains MySQL');
check(/model\s+ProviderWebhookEvent\s*\{/.test(schema), 'Provider webhook event model exists');
check(/@@unique\(\[providerName,\s*providerEventId\]\)/.test(schema), 'Provider event idempotency constraint exists');
check(migration.includes('CREATE TABLE `ProviderWebhookEvent`'), 'MySQL migration creates webhook registry');
check(migration.includes('ProviderWebhookEvent_providerName_providerEventId_key'), 'Migration includes unique provider event key');
check(safety.includes('timingSafeEqual') && safety.includes('createHmac'), 'Webhook signature verification uses constant-time HMAC comparison');
check(safety.includes('Number.isSafeInteger(amountPaise)') && safety.includes('Duplicate statement row'), 'Statement parser validates paise amounts and duplicate rows');
check(safety.includes('interface PayoutProviderAdapter') && safety.includes('idempotencyKey'), 'Provider adapter contract requires idempotency key');
check(tests.includes('rejects duplicate, invalid and malformed statement rows'), 'Unit tests cover invalid statement inputs');
if (failed) process.exit(1);
