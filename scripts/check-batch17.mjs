import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const assert = (condition, message) => { if (!condition) { console.error(`FAIL: ${message}`); process.exitCode = 1; } else console.log(`PASS: ${message}`); };
const schema = read('prisma/schema.prisma');
const migration = read('prisma/migrations/202610140017_payout_reconciliation_disputes/migration.sql');
const service = read('apps/api/src/payouts/payouts.service.ts');
const controller = read('apps/api/src/payouts/payouts.controller.ts');
const app = read('apps/api/src/app.module.ts');
const ui = read('apps/web/app/finance/payouts/page.tsx');
assert(/provider\s*=\s*"mysql"/.test(schema), 'Prisma datasource remains MySQL');
for (const model of ['PayoutBatch','PayoutItem','FinanceDispute']) assert(new RegExp(`model\\s+${model}\\s*\\{`).test(schema), `${model} Prisma model exists`);
for (const table of ['PayoutBatch','PayoutItem','FinanceDispute']) assert(migration.includes(`CREATE TABLE \`${table}\``), `${table} MySQL migration exists`);
assert(/ledgerEntryId\s+String\s+@unique/.test(schema), 'Payout item ledger entry assignment is unique');
assert(service.includes('Maker-checker rule') && service.includes('createdById === actor.sub'), 'Maker-checker rule is enforced');
assert(service.includes('ownerIdentityVerified') && service.includes('kycReviewed') && service.includes('fraudReviewed') && service.includes('taxReviewCompleted'), 'Compliance review attestations are required');
assert(service.includes("item.status === 'PAID' && !item.providerReference?.trim()"), 'Paid reconciliation requires provider reference');
assert(service.includes('REWARD_ACCRUAL') && service.includes("entry.calculation.status !== 'APPROVED'"), 'Only approved reward accruals can enter payout batch');
assert(service.includes('FINANCE_DISPUTE_OPENED') && service.includes('PayoutItemStatus.DISPUTED'), 'Disputes are audited and block unsettled payout items');
assert(controller.includes('@UseGuards(JwtAuthGuard, RolesGuard)'), 'Payout controller requires JWT and role guard');
assert(app.includes('PayoutsModule'), 'Payout module registered in application');
assert(ui.includes('/finance/payout-batches') && ui.includes('/finance/disputes'), 'Finance payout and dispute page calls API');
