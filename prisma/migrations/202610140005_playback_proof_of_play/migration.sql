CREATE TABLE `PlaybackEvent` (
  `id` VARCHAR(30) NOT NULL,
  `organizationId` VARCHAR(30) NOT NULL,
  `screenId` VARCHAR(30) NOT NULL,
  `assetId` VARCHAR(30) NOT NULL,
  `campaignId` VARCHAR(30) NULL,
  `playlistId` VARCHAR(30) NULL,
  `eventId` VARCHAR(100) NOT NULL,
  `eventType` ENUM('PLAY_STARTED','PLAY_COMPLETED','PLAY_INTERRUPTED','PLAY_ERROR') NOT NULL,
  `status` ENUM('RECEIVED','ACCEPTED','REJECTED','DUPLICATE') NOT NULL DEFAULT 'RECEIVED',
  `startedAt` DATETIME(3) NULL,
  `completedAt` DATETIME(3) NULL,
  `durationMs` INTEGER NULL,
  `expectedDurationMs` INTEGER NULL,
  `sequenceNumber` BIGINT NULL,
  `clientReportedAt` DATETIME(3) NULL,
  `receivedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `validationReason` VARCHAR(255) NULL,
  `metadataJson` JSON NULL,
  UNIQUE INDEX `PlaybackEvent_screenId_eventId_key` (`screenId`,`eventId`),
  INDEX `PlaybackEvent_organizationId_status_receivedAt_idx` (`organizationId`,`status`,`receivedAt`),
  INDEX `PlaybackEvent_screenId_eventType_completedAt_idx` (`screenId`,`eventType`,`completedAt`),
  INDEX `PlaybackEvent_campaignId_status_completedAt_idx` (`campaignId`,`status`,`completedAt`),
  INDEX `PlaybackEvent_assetId_status_completedAt_idx` (`assetId`,`status`,`completedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `PlaybackEvent_screenId_fkey` FOREIGN KEY (`screenId`) REFERENCES `Screen`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `PlaybackEvent_assetId_fkey` FOREIGN KEY (`assetId`) REFERENCES `MediaAsset`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `PlaybackEvent_campaignId_fkey` FOREIGN KEY (`campaignId`) REFERENCES `Campaign`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `PlaybackEvent_playlistId_fkey` FOREIGN KEY (`playlistId`) REFERENCES `Playlist`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `PlaybackEvent_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
