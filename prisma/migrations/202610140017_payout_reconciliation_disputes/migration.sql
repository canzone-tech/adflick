-- BATCH 17: payout batch workflow and finance disputes. MySQL 8.4.
CREATE TABLE `PayoutBatch` (
  `id` VARCHAR(30) NOT NULL,
  `organizationId` VARCHAR(30) NOT NULL,
  `batchReference` VARCHAR(80) NOT NULL,
  `status` ENUM('DRAFT','PENDING_APPROVAL','APPROVED','EXPORTED','SUBMITTED_TO_PROVIDER','RECONCILIATION_REQUIRED','PARTIALLY_RECONCILED','RECONCILED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
  `currency` CHAR(3) NOT NULL DEFAULT 'INR',
  `totalAmountPaise` INTEGER NOT NULL DEFAULT 0,
  `itemCount` INTEGER NOT NULL DEFAULT 0,
  `createdById` VARCHAR(30) NOT NULL,
  `approvedById` VARCHAR(30) NULL,
  `approvalNote` VARCHAR(500) NULL,
  `providerName` VARCHAR(100) NULL,
  `providerBatchReference` VARCHAR(160) NULL,
  `exportedAt` DATETIME(3) NULL,
  `submittedAt` DATETIME(3) NULL,
  `reconciledAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`), UNIQUE INDEX `PayoutBatch_batchReference_key` (`batchReference`),
  INDEX `PayoutBatch_organizationId_status_createdAt_idx` (`organizationId`,`status`,`createdAt`),
  CONSTRAINT `PayoutBatch_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `PayoutItem` (
  `id` VARCHAR(30) NOT NULL,
  `organizationId` VARCHAR(30) NOT NULL,
  `payoutBatchId` VARCHAR(30) NOT NULL,
  `ledgerEntryId` VARCHAR(30) NOT NULL,
  `ownerUserId` VARCHAR(30) NOT NULL,
  `amountPaise` INTEGER NOT NULL,
  `currency` CHAR(3) NOT NULL DEFAULT 'INR',
  `status` ENUM('PENDING','EXPORTED','SUBMITTED','PAID','FAILED','HELD','DISPUTED','REVERSED') NOT NULL DEFAULT 'PENDING',
  `ownerIdentityVerified` BOOLEAN NOT NULL DEFAULT false,
  `kycReviewed` BOOLEAN NOT NULL DEFAULT false,
  `fraudReviewed` BOOLEAN NOT NULL DEFAULT false,
  `taxReviewCompleted` BOOLEAN NOT NULL DEFAULT false,
  `providerReference` VARCHAR(160) NULL,
  `reconciliationNote` VARCHAR(500) NULL,
  `reconciledAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`), UNIQUE INDEX `PayoutItem_ledgerEntryId_key` (`ledgerEntryId`),
  INDEX `PayoutItem_organizationId_status_createdAt_idx` (`organizationId`,`status`,`createdAt`),
  INDEX `PayoutItem_payoutBatchId_status_idx` (`payoutBatchId`,`status`),
  INDEX `PayoutItem_ownerUserId_createdAt_idx` (`ownerUserId`,`createdAt`),
  CONSTRAINT `PayoutItem_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `PayoutItem_batch_fkey` FOREIGN KEY (`payoutBatchId`) REFERENCES `PayoutBatch` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `PayoutItem_ledgerEntry_fkey` FOREIGN KEY (`ledgerEntryId`) REFERENCES `RewardLedgerEntry` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `FinanceDispute` (
  `id` VARCHAR(30) NOT NULL,
  `organizationId` VARCHAR(30) NOT NULL,
  `ledgerEntryId` VARCHAR(30) NOT NULL,
  `openedById` VARCHAR(30) NOT NULL,
  `assignedToId` VARCHAR(30) NULL,
  `status` ENUM('OPEN','UNDER_REVIEW','RESOLVED_OWNER_FAVOUR','RESOLVED_ORGANIZATION_FAVOUR','CLOSED') NOT NULL DEFAULT 'OPEN',
  `reasonCode` VARCHAR(80) NOT NULL,
  `description` VARCHAR(1000) NOT NULL,
  `resolutionNote` VARCHAR(1000) NULL,
  `resolvedById` VARCHAR(30) NULL,
  `resolvedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`), INDEX `FinanceDispute_organizationId_status_createdAt_idx` (`organizationId`,`status`,`createdAt`),
  INDEX `FinanceDispute_ledgerEntryId_status_idx` (`ledgerEntryId`,`status`),
  CONSTRAINT `FinanceDispute_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `FinanceDispute_ledgerEntryId_fkey` FOREIGN KEY (`ledgerEntryId`) REFERENCES `RewardLedgerEntry` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
