CREATE TABLE `Incident` (
  `id` VARCHAR(30) NOT NULL,
  `organizationId` VARCHAR(30) NOT NULL,
  `screenId` VARCHAR(30) NULL,
  `title` VARCHAR(180) NOT NULL,
  `description` TEXT NULL,
  `category` ENUM('SCREEN_OFFLINE','PLAYER_ERROR','RESOURCE_PRESSURE','COMMAND_FAILURE','SYNC_FAILURE','OTHER') NOT NULL DEFAULT 'OTHER',
  `severity` ENUM('LOW','MEDIUM','HIGH','CRITICAL') NOT NULL DEFAULT 'MEDIUM',
  `status` ENUM('OPEN','ACKNOWLEDGED','IN_PROGRESS','RESOLVED','DISMISSED') NOT NULL DEFAULT 'OPEN',
  `openedById` VARCHAR(30) NOT NULL,
  `assignedToId` VARCHAR(30) NULL,
  `acknowledgedAt` DATETIME(3) NULL,
  `resolvedAt` DATETIME(3) NULL,
  `resolutionNote` VARCHAR(1000) NULL,
  `lastNotifiedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  INDEX `Incident_organizationId_status_severity_createdAt_idx` (`organizationId`,`status`,`severity`,`createdAt`),
  INDEX `Incident_screenId_status_createdAt_idx` (`screenId`,`status`,`createdAt`),
  INDEX `Incident_assignedToId_status_idx` (`assignedToId`,`status`),
  PRIMARY KEY (`id`),
  CONSTRAINT `Incident_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `Incident_screenId_fkey` FOREIGN KEY (`screenId`) REFERENCES `Screen`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
